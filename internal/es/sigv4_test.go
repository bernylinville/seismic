package es

import (
	"context"
	"encoding/json"
	"io"
	"net/http"
	"net/url"
	"os"
	"strings"
	"testing"
	"time"
)

type sigv4Vector struct {
	Name              string            `json:"name"`
	Method            string            `json:"method"`
	URL               string            `json:"url"`
	Headers           map[string]string `json:"headers"`
	Body              string            `json:"body"`
	SessionToken      string            `json:"sessionToken"`
	WantAuthorization string            `json:"wantAuthorization"`
}

const vectorFixedTime = "2026-10-12T06:50:22Z"

// TestSigV4ParityWithAws4fetch signs the same requests as the real aws4fetch
// (testdata/aws4fetch.mjs, pinned upstream) and requires byte-identical
// Authorization headers. Vectors are generated by that library itself.
func TestSigV4ParityWithAws4fetch(t *testing.T) {
	data, err := os.ReadFile("testdata/sigv4_vectors.json")
	if err != nil {
		t.Fatal(err)
	}
	var vectors []sigv4Vector
	if err := json.Unmarshal(data, &vectors); err != nil {
		t.Fatal(err)
	}
	if len(vectors) == 0 {
		t.Fatal("no vectors")
	}

	fixed, _ := time.Parse(time.RFC3339, vectorFixedTime)
	for _, v := range vectors {
		t.Run(v.Name, func(t *testing.T) {
			s, err := newSigV4Signer("AKIDEXAMPLE", "wJalrXUtnFEMI/K7MDENG+bPxRfiCYEXAMPLEKEY", v.SessionToken, "us-east-1", "es")
			if err != nil {
				t.Fatal(err)
			}
			s.now = func() time.Time { return fixed }

			u, err := url.Parse(v.URL)
			if err != nil {
				t.Fatal(err)
			}
			req := &http.Request{
				Method: v.Method,
				URL:    u,
				Header: http.Header{},
			}
			for k, val := range v.Headers {
				req.Header.Set(k, val)
			}
			if v.Body != "" {
				req.Body = io.NopCloser(strings.NewReader(v.Body))
				req.ContentLength = int64(len(v.Body))
			}

			if err := s.sign(context.Background(), req); err != nil {
				t.Fatal(err)
			}
			if got := req.Header.Get("Authorization"); got != v.WantAuthorization {
				t.Errorf("Authorization mismatch\n got: %s\nwant: %s", got, v.WantAuthorization)
			}
			if got := req.Header.Get("X-Amz-Date"); got != "20261012T065022Z" {
				t.Errorf("X-Amz-Date = %q", got)
			}
		})
	}
}
